"""
gen_arm_dataset.py

Generates an on-disk dataset of arm poses for the no-object LIBERO scene.

Each sample is produced by:
  1. Resetting the environment to its initial state.
  2. Applying a random number of random-action steps (between MIN_STEPS and
     MAX_STEPS), where each action dimension is independently clamped to the
     configured limits.
  3. Capturing the final obs (image + full obs dict) as one dataset entry.

The dataset is saved as a single compressed .npz file:
    <output_dir>/arm_dataset.npz

  Keys in the .npz:
    images       uint8  (N, H, W, 3)   agentview images (already flipped)
    eef_pos      float32 (N, 3)        robot0_eef_pos
    eef_quat     float32 (N, 4)        robot0_eef_quat  (w, x, y, z)
    joint_pos    float32 (N, 7)        robot0_joint_pos (7 arm joints)
    obs_keys     str                   JSON list of all obs keys saved in obs_dicts
    obs_dicts    object  (N,)          array of dicts (dtype=object), one per sample
                                       each dict maps obs_key -> np.ndarray

Loading the dataset later:
    data = np.load("arm_dataset.npz", allow_pickle=True)
    images    = data["images"]           # (N, H, W, 3)
    eef_pos   = data["eef_pos"]          # (N, 3)
    eef_quat  = data["eef_quat"]         # (N, 4)
    obs_dicts = data["obs_dicts"]        # array of dicts
    # Reconstruct as GoalSample:
    #   GoalSample(obs=obs_dicts[i], image=images[i], position=eef_pos[i], quat=eef_quat[i])

Usage:
    python gen_arm_dataset.py --nb_goals 10000
    python gen_arm_dataset.py --nb_goals 50000 --output_dir my_dataset --seed 42
"""
import argparse
import json
import logging
import os
import tempfile
from datetime import datetime

import imageio
import numpy as np
from tqdm import tqdm

# ---------------------------------------------------------------------------
# Config  (edit these directly — no Hydra needed for a standalone script)
# ---------------------------------------------------------------------------

CFG = {
    # --- Scene ---
    "camera_heights": 224,
    "camera_widths":  224,
    "camera_key":     "agentview_image",

    # --- Episode randomisation ---
    # Each goal is generated by resetting and then taking between
    # MIN_STEPS and MAX_STEPS random actions.
    "min_steps": 40,
    "max_steps": 200,

    # --- Action limits per dimension ---
    # LIBERO actions: [dx, dy, dz, droll, dpitch, dyaw, gripper]
    # Each entry is [lo, hi] — action is sampled uniformly in this range.
    #
    # Actions are EEF *delta* commands, clipped internally by the controller
    # to whatever is physically feasible. Using large values is safe — the
    # controller will simply saturate at the joint limits rather than
    # teleporting the arm. This is the right way to drive the arm to diverse
    # positions without worrying about collision.
    #
    # Gripper is fixed open (0.0) — no point varying it for a reaching task.
    "action_limits": [
        [-1.0,  1.0],   # dx
        [-1.0,  1.0],   # dy
        [-1.0,  1.0],   # dz
        [-1.0,  1.0],   # droll
        [-1.0,  1.0],   # dpitch
        [-1.0,  1.0],   # dyaw
        [ 0.0,  0.0],   # gripper — fixed open
    ],

    # --- Misc ---
    "action_dim": 7,
    "log_interval": 500,   # log progress every N goals
}

# ---------------------------------------------------------------------------
# Logging
# ---------------------------------------------------------------------------

logger = logging.getLogger(__name__)


def init_logging(output_dir: str, log_level: str) -> None:
    root = logging.getLogger()
    root.setLevel(logging.DEBUG)

    fmt = logging.Formatter("%(asctime)s - %(levelname)s - %(message)s")

    ch = logging.StreamHandler()
    ch.setLevel(log_level.upper())
    ch.setFormatter(fmt)
    root.addHandler(ch)

    fh = logging.FileHandler(os.path.join(output_dir, "gen_arm_dataset.log"))
    fh.setLevel(logging.DEBUG)
    fh.setFormatter(fmt)
    root.addHandler(fh)


# ---------------------------------------------------------------------------
# BDDL  (inline — no object, just the robot arm)
# ---------------------------------------------------------------------------

BDDL_ARM = """\
(define (problem libero_custom_single_object)
  (:domain robosuite)
  (:language arm only scene for dataset generation)
  (:regions
    (table_region
        (:target main_table)
        (:ranges (
            (-0.3 -0.3 0.3 0.3)
          )
        )
    )
  )
  (:fixtures
    main_table - table
  )
  (:objects
  )
  (:init
  )
  (:goal
    (And )
  )
)
"""


def write_arm_bddl() -> str:
    tmp = tempfile.NamedTemporaryFile(
        mode="w", suffix=".bddl", delete=False, prefix="libero_arm_dataset_"
    )
    tmp.write(BDDL_ARM)
    tmp.flush()
    logger.info("BDDL written to: %s", tmp.name)
    return tmp.name


# ---------------------------------------------------------------------------
# Dataset generation
# ---------------------------------------------------------------------------

def sample_action(rng: np.random.Generator, action_limits: list) -> list:
    """Sample one random action within the configured per-dimension limits."""
    return [
        float(rng.uniform(lo, hi))
        for lo, hi in action_limits
    ]


def generate_dataset(nb_goals: int, output_dir: str, seed: int) -> str:
    """
    Generate nb_goals arm-pose samples and save to <output_dir>/arm_dataset.npz.

    Returns the path to the saved file.
    """
    from libero.libero.envs import OffScreenRenderEnv

    rng = np.random.default_rng(seed)
    camera_key = CFG["camera_key"]
    action_limits = CFG["action_limits"]
    action_dim = CFG["action_dim"]
    min_steps = CFG["min_steps"]
    max_steps = CFG["max_steps"]

    # --- Build environment ---
    bddl_path = write_arm_bddl()
    env = OffScreenRenderEnv(
        bddl_file_name=bddl_path,
        hard_reset=False,
        camera_heights=CFG["camera_heights"],
        camera_widths=CFG["camera_widths"],
    )
    env.seed(seed)
    env.reset()
    logger.info("Environment ready. Generating %d goals...", nb_goals)

    # --- Pre-allocate arrays for the fast-access fields ---
    H, W = CFG["camera_heights"], CFG["camera_widths"]
    images    = np.zeros((nb_goals, H, W, 3), dtype=np.uint8)
    eef_pos   = np.zeros((nb_goals, 3),       dtype=np.float32)
    eef_quat  = np.zeros((nb_goals, 4),       dtype=np.float32)
    joint_pos = np.zeros((nb_goals, 7),       dtype=np.float32)  # 7 arm joints
    obs_dicts = np.empty(nb_goals, dtype=object)

    total_steps = 0

    for i in tqdm(range(nb_goals), desc="Generating arm goals"):
        # Reset to initial state and settle physics with a few no-op steps.
        # hard_reset=False means the MuJoCo model is not reloaded each time
        # (fast), but we must let the controller reinitialise by stepping.
        env.reset()
        for _ in range(10):
            env.step([0.0] * action_dim)

        # Take a random number of random-action steps
        n_steps = int(rng.integers(min_steps, max_steps + 1))
        logger.debug("Goal %d: taking %d random steps...", i, n_steps)
        obs = None
        for _ in range(n_steps):
            action = sample_action(rng, action_limits)
            obs, _, done, _ = env.step(action)
            #if done:
            #    logger.warning("Environment terminated early at step %d for goal %d. Resetting...", _, i)
            #    # Environment terminated early (shouldn't happen without objects,
            #    # but handle gracefully by resetting)
            #    env.reset()
            #    for _ in range(10):
            #        env.step([0.0] * action_dim)

        total_steps += n_steps

        if obs is None:
            # Fallback: take one no-op step
            obs, _, _, _ = env.step([0.0] * action_dim)

        # --- Extract fields ---
        # Image: flip y-axis (MuJoCo renders upside-down)
        images[i] = obs[camera_key][::-1].copy()

        ep = obs.get("robot0_eef_pos")
        eq = obs.get("robot0_eef_quat")
        jp = obs.get("robot0_joint_pos")

        if ep is not None:
            eef_pos[i] = np.array(ep, dtype=np.float32)
        else:
            logger.warning("Sample %d: 'robot0_eef_pos' missing from obs.", i)

        if eq is not None:
            eef_quat[i] = np.array(eq, dtype=np.float32)
        else:
            logger.warning("Sample %d: 'robot0_eef_quat' missing from obs.", i)

        if jp is not None:
            joint_pos[i] = np.array(jp, dtype=np.float32)
        else:
            logger.warning("Sample %d: 'robot0_joint_pos' missing from obs.", i)

        # Store full obs dict (all values converted to float32 arrays)
        obs_dicts[i] = {k: np.array(v, dtype=np.float32) for k, v in obs.items()
                        if k != camera_key}  # image already stored separately

        if (i + 1) % CFG["log_interval"] == 0 or (i + 1) == nb_goals:
            logger.info(
                "Progress: %d / %d  (avg %.1f steps/goal)",
                i + 1, nb_goals, total_steps / (i + 1),
            )

    env.close()

    # --- Save ---
    # Collect all obs keys present across samples (should be identical for all)
    obs_keys = sorted(obs_dicts[0].keys()) if nb_goals > 0 else []

    out_path = os.path.join(output_dir, "arm_dataset.npz")
    np.savez_compressed(
        out_path,
        images=images,
        eef_pos=eef_pos,
        eef_quat=eef_quat,
        joint_pos=joint_pos,
        obs_keys=json.dumps(obs_keys),
        obs_dicts=obs_dicts,
    )
    logger.info("Dataset saved to: %s  (%d samples)", out_path, nb_goals)
    logger.info("Total env steps taken: %d  (avg %.1f per goal)", total_steps, total_steps / nb_goals)
    return out_path


# ---------------------------------------------------------------------------
# Optional: save a preview video of the first N samples
# ---------------------------------------------------------------------------

def save_preview(npz_path: str, output_dir: str, n: int = 100) -> None:
    data = np.load(npz_path, allow_pickle=True)
    frames = list(data["images"][:n])
    video_path = os.path.join(output_dir, "preview.mp4")
    imageio.mimsave(video_path, frames, fps=10)
    logger.info("Preview video saved to: %s  (%d frames)", video_path, len(frames))


# ---------------------------------------------------------------------------
# Optional: dump all images as individual .png files
# ---------------------------------------------------------------------------

def dump_images(npz_path: str, img_dir: str) -> None:
    os.makedirs(img_dir, exist_ok=True)
    data = np.load(npz_path, allow_pickle=True)
    images = data["images"]
    n = len(images)
    # Zero-pad filenames so they sort correctly (e.g. 00000.png .. 49999.png)
    pad = len(str(n - 1))
    for i, img in enumerate(images):
        path = os.path.join(img_dir, f"{str(i).zfill(pad)}.png")
        imageio.imwrite(path, img)
        if (i + 1) % CFG["log_interval"] == 0 or (i + 1) == n:
            logger.info("Dumped %d / %d images to %s", i + 1, n, img_dir)
    logger.info("All %d images saved to: %s", n, img_dir)


# ---------------------------------------------------------------------------
# Entry point
# ---------------------------------------------------------------------------

def main():
    parser = argparse.ArgumentParser(
        description="Generate an on-disk dataset of arm poses for the no-object LIBERO scene."
    )
    parser.add_argument(
        "--nb_goals",
        type=int,
        required=True,
        help="Number of goal images/obs to generate.",
    )
    parser.add_argument(
        "--output_dir",
        type=str,
        default=None,
        help="Directory to save the dataset. Defaults to output/<timestamp>_arm_dataset/",
    )
    parser.add_argument(
        "--seed",
        type=int,
        default=42,
        help="Random seed for reproducibility.",
    )
    parser.add_argument(
        "--preview",
        action="store_true",
        help="Save a short preview video of the first 100 samples.",
    )
    parser.add_argument(
        "--dump_img",
        type=str,
        default=None,
        metavar="IMG_DIR",
        help="If set, dump all generated images as .png files into IMG_DIR.",
    )
    parser.add_argument(
        "--log_level",
        default="INFO",
        choices=["DEBUG", "INFO", "WARNING", "ERROR", "CRITICAL"],
    )
    args = parser.parse_args()

    # --- Output directory ---
    if args.output_dir is None:
        date_prefix = datetime.now().strftime("%Y-%m-%d-%H-%M-%S")
        args.output_dir = os.path.join("output", f"{date_prefix}_arm_dataset")
    os.makedirs(args.output_dir, exist_ok=True)

    init_logging(args.output_dir, args.log_level)

    logger.info("========================================")
    logger.info("gen_arm_dataset.py")
    logger.info("  nb_goals   : %d", args.nb_goals)
    logger.info("  output_dir : %s", args.output_dir)
    logger.info("  seed       : %d", args.seed)
    logger.info("  dump_img   : %s", args.dump_img or "(disabled)")
    logger.info("========================================")

    npz_path = generate_dataset(
        nb_goals=args.nb_goals,
        output_dir=args.output_dir,
        seed=args.seed,
    )

    if args.preview:
        save_preview(npz_path, args.output_dir)

    if args.dump_img is not None:
        dump_images(npz_path, args.dump_img)

    logger.info("Done.")


if __name__ == "__main__":
    main()