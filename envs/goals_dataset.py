"""
GoalsDataset: a fixed dataset of (image, object_position) goal pairs
generated by randomising the object position within a configured workspace.

Each goal is captured with the arm parked out of frame so the image
shows only the table and the object at its goal location.

Usage:
    dataset = GoalsDataset(cfg, env)
    dataset.generate()          # populate the dataset
    goal = dataset.sample_goal() # returns a GoalSample namedtuple
    goal.image                   # uint8 (H, W, 3)
    goal.position                # float32 (3,)  world-frame xyz
"""
import logging
from dataclasses import dataclass
from typing import List, Dict
from tqdm import tqdm
from PIL import Image

import numpy as np
from omegaconf import DictConfig

from envs.libero_env import LiberoEnv, PARK_QPOS, set_arm_qpos, get_object_pos

logger = logging.getLogger(__name__)


@dataclass
class GoalSample:
    """A single goal: the image the agent should reach and the object position."""
    obs: Dict[str, np.ndarray]  # full obs dict (image + proprio + object positions)
    image: np.ndarray       # uint8 (H, W, 3)
    position: np.ndarray    # float32 (3,)  world-frame xyz

    def save_image_to_file(self, image_path: str) -> None:
        Image.fromarray(self.image[::-1]).save(image_path)



class GoalsDataset:
    """
    Holds a fixed dataset of goals generated by randomising the object
    position within a workspace rectangle defined in the Hydra config.

    Generation procedure for each goal:
        1. Reset the environment.
        2. Sample a random (x, y) within the configured workspace limits.
        3. Teleport the object to (x, y) via LiberoEnv.set_object_position().
        4. Park the arm out of frame via set_arm_qpos(PARK_QPOS).
        5. Capture the agentview image and read the object position from obs.
        6. Store as a GoalSample.

    After generation the arm is restored to the neutral pose and the
    environment is reset so it is ready for normal use.
    """

    def __init__(self, cfg: DictConfig, env: LiberoEnv):
        """
        Args:
            cfg: full Hydra config (cfg.goals sub-config is used)
            env: an already-initialised LiberoEnv instance
        """
        self.cfg = cfg
        self.env = env
        self._goals: List[GoalSample] = []

        # Resolve object position key
        self._object_pos_key: str = (
            cfg.goals.object_pos_key
            if cfg.goals.object_pos_key is not None
            else f"{cfg.env.object_name}_1_pos"
        )
        self._camera_key: str = cfg.goals.camera_key

        logger.info(
            "GoalsDataset: n_goals=%d, workspace x=[%.3f, %.3f] y=[%.3f, %.3f], "
            "camera=%s, pos_key=%s",
            cfg.goals.n_goals,
            cfg.goals.x_min, cfg.goals.x_max,
            cfg.goals.y_min, cfg.goals.y_max,
            self._camera_key,
            self._object_pos_key,
        )

    # ------------------------------------------------------------------
    # Public API
    # ------------------------------------------------------------------

    def generate(self) -> None:
        """
        Generate cfg.goals.n_goals goals and store them internally.

        This method resets the environment before starting and restores
        it to a clean reset state when done.
        """
        n = self.cfg.goals.n_goals
        logger.info("Generating %d goals...", n)

        self._goals = []
        rng = np.random.default_rng(self.cfg.seed)

        # Sample all positions upfront for reproducibility
        xs = rng.uniform(self.cfg.goals.x_min, self.cfg.goals.x_max, size=n)
        ys = rng.uniform(self.cfg.goals.y_min, self.cfg.goals.y_max, size=n)

        for i in tqdm(range(n), desc="Generating goals"):
            goal = self._capture_goal(xs[i], ys[i])
            self._goals.append(goal)


        # Restore env to a clean state after goal generation
        self.env.reset()
        logger.info("Goal generation complete. Dataset size: %d", len(self._goals))

    def sample_goal(self) -> GoalSample:
        """
        Return a randomly selected goal from the dataset.

        Raises:
            RuntimeError: if generate() has not been called yet.
        """
        if not self._goals:
            raise RuntimeError(
                "GoalsDataset is empty. Call generate() before sample_goal()."
            )
        idx = np.random.randint(0, len(self._goals))
        return self._goals[idx]

    def __len__(self) -> int:
        return len(self._goals)

    def __getitem__(self, idx: int) -> GoalSample:
        return self._goals[idx]

    # ------------------------------------------------------------------
    # Internal helpers
    # ------------------------------------------------------------------

    def _capture_goal(self, x: float, y: float) -> GoalSample:
        """
        Move the object to (x, y), park the arm, capture image + position.

        Returns:
            GoalSample with image and position
        """
        # 1. Reset to a clean state
        self.env.reset()

        # 2. Teleport object to target position and let physics settle
        obs = self.env.set_object_position(
            x=x,
            y=y,
            n_settle=self.cfg.goals.n_settle,
        )

        # 3. Park the arm out of frame and settle again
        #obs = set_arm_qpos(
        #    self.env._env,
        #    PARK_QPOS,
        #    n_settle=self.cfg.goals.n_settle,
        #)

        if obs is None:
            raise RuntimeError(
                "set_arm_qpos returned None — environment may not be stepping correctly."
            )

        # 4. Extract image
        image = obs[self._camera_key].copy()   # uint8 (H, W, 3)

        # 5. Extract object position
        position = get_object_pos(obs, self.cfg.env.object_name)
        if position is None:
            # Fallback: use the requested (x, y) with z=0.97 (table surface)
            logger.warning(
                "Could not read object position from obs for goal (%s, %s). "
                "Using requested (x, y) with z=0.97 as fallback.",
                x, y,
            )
            position = np.array([x, y, 0.97], dtype=np.float32)
        else:
            position = position.astype(np.float32)

        logger.debug(
            "Goal captured: requested=(%.4f, %.4f), actual=(%.4f, %.4f, %.4f)",
            x, y, position[0], position[1], position[2],
        )
        return GoalSample(obs=obs, image=image, position=position)
